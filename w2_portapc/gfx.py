PIX = {'.': 0, '#': 1, '+': 9, 'o': 10}


def _frame(rows, shift):
    tiles = bytearray(16 * 32)
    for y, row in enumerate(rows):
        for x in range(32):
            sx = x - shift
            v = PIX[row[sx]] if 0 <= sx < 32 else 0
            t = (y // 8) * 4 + x // 8
            i = t * 32 + (y % 8) * 4 + (x % 8) // 2
            tiles[i] |= v << 4 if x & 1 else v
    return bytes(tiles)


def pc_icon(orig_ncgr):
    """Replace the character data of a two-frame 32x32 icon NCGR (frame 2 moved 1 px right,
    like the vanilla icons)."""
    assert len(PC_ICON) == 32 and all(len(r) == 32 for r in PC_ICON)
    o = orig_ncgr.find(b'RAHC')
    size, off = struct.unpack_from('<II', orig_ncgr, o + 0x18)
    if size != 1024:
        raise ValueError('unexpected icon size')
    data = _frame(PC_ICON, 0) + _frame(PC_ICON, 1)
    return orig_ncgr[:o + 8 + off] + data + orig_ncgr[o + 8 + off + size:]


def add_bar_button(nscr):
    """Draw a 3-tile-high button at rows 21-23, columns 0-15 (under the left half of the
    bottom bar), made from rows 15/17/19 of the button at rows 15-19."""
    o = nscr.find(b'NRCS')
    w = struct.unpack_from('<H', nscr, o + 8)[0] // 8
    base = o + 0x14
    out = bytearray(nscr)
    for dst, src in ((21, 15), (22, 17), (23, 19)):
        for c in range(16):
            if struct.unpack_from('<H', out, base + 2 * (dst * w + c))[0] & 0x3FF:
                raise ValueError('bottom rows of the button tilemap are not empty')
            v = struct.unpack_from('<H', nscr, base + 2 * (src * w + c))[0]
            struct.pack_into('<H', out, base + 2 * (dst * w + c), v)
    return bytes(out)
